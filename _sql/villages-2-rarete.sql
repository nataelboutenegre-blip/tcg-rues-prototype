select
  coalesce(c.tier, '(absent de la base)')        as rarete,
  count(*)                                       as villages,
  count(p.commune_code)                          as deja_pris,
  count(*) - count(p.commune_code)               as encore_libres
  from liste l
  left join public.communes    c on c.code = l.code
  left join public.possessions p on p.commune_code = l.code
 group by coalesce(c.tier, '(absent de la base)')
 order by villages desc;
