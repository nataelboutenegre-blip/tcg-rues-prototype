# Ne touche PAS aux points du classement Front (score), aux points d'Elo, ni aux « points » de chances.
# Ne touche pas aux règles de la saison 1 (cachées en saison 2).
import pathlib
def appliquer(nom, changements):
    f = pathlib.Path(nom); lignes = f.read_text(encoding='utf-8').split('\n')
    for n, avant, apres, nb in changements:
        l = lignes[n - 1]
        assert l.count(avant) == nb, (nom, n, avant, l.count(avant))
        lignes[n - 1] = l.replace(avant, apres)
    f.write_text('\n'.join(lignes), encoding='utf-8')

